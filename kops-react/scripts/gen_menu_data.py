"""menu_cases.json -> TypeScript menu catalog for the React UI."""
import json, pathlib, re

root = pathlib.Path(__file__).resolve().parents[1]
cases = json.loads((root / "data/menu_cases.json").read_text(encoding="utf-8"))["cases"]
out = []
for c in cases:
    parts = [p.strip() for p in c["path"].split(">")]
    group = parts[0]
    uris = set()
    for e in c.get("expected_uris", []):
        uris.add(e.get("slug") or e["uri"].rsplit("/", 1)[-1])
    for s in c["steps"]:
        if s["do"] == "expect_any":
            uris.update(u.rsplit("/", 1)[-1] for u in s.get("uris", []))
        if s["do"] == "expect" and s.get("uri"):
            uris.add(s["uri"].rsplit("/", 1)[-1])
    out.append({
        "id": c["menu_id"],
        "path": c["path"],
        "title": c["screen"]["title"] or parts[-1],
        "group": group,
        "section": parts[1] if len(parts) > 1 else group,
        "depth": len(parts),
        "loginRequired": bool(c.get("login_required")),
        "appUri": c["screen"].get("app_uri"),
        "sample": c.get("sample", {}),
        "searchLabels": sorted({s["label"] for s in c["steps"]
                                if s["do"] in ("select", "fill", "click", "popup") and s.get("label")}),
        "detailIds": [s["menu_id"] for s in c["steps"] if s["do"] == "detail"],
        "detailNames": sorted({s.get("name", "") for s in c["steps"] if s["do"] == "detail"}),
        "uris": sorted(uris),
    })

body = json.dumps(out, ensure_ascii=False, indent=2)
(root / "src/data/menuCases.ts").write_text(
    "// Generated by scripts/gen_menu_data.py — do not edit by hand.\n"
    "export interface MenuCase {\n"
    "  id: string;\n  path: string;\n  title: string;\n  group: string;\n"
    "  section: string;\n  depth: number;\n  loginRequired: boolean;\n"
    "  appUri: string | null;\n  sample: Record<string, string>;\n"
    "  searchLabels: string[];\n  detailIds: string[];\n  detailNames: string[];\n"
    "  uris: string[];\n}\n\n"
    "export const MENU_CASES: MenuCase[] = " + body + ";\n\n"
    "export const MENU_BY_ID: Record<string, MenuCase> = Object.fromEntries(\n"
    "  MENU_CASES.map((menu) => [menu.id, menu]),\n);\n\n"
    "export const MENU_GROUPS: string[] = Array.from(\n"
    "  new Set(MENU_CASES.map((menu) => menu.group)),\n);\n\n"
    "export const FORM_TYPES = [\n"
    "  '견본품 제공',\n  '학술대회 지원',\n  '임상시험 등의 지원',\n  '제품설명회',\n"
    "  '시판 후 조사',\n  '대금결제 조건에 따른 비용할인',\n"
    "  '구매 전 의료기기의 성능 확인을 위한 사용',\n];\n",
    encoding="utf-8",
)
print(f"generated {len(out)} menus")
